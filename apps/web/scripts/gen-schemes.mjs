// Generates src/styles/schemes.css (color schemes + chart palettes) and validates them.
// Run: node scripts/gen-schemes.mjs [--validate PATH_TO_validate_palette.js]
// Base colors are each scheme's official hex values; chart colors are derived in OKLCH (see CHART below).
import { writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'

import { contrast, ensure, fromOklch, toOklch } from './color.mjs'

// ---- schemes: official hex values ----
// [bg, card, fg, mutedBg (secondary/muted/accent fill), mutedFg, border, primary, destructive]
const S = {
  catppuccin: {
    light: ['#eff1f5', '#e6e9ef', '#4c4f69', '#ccd0da', '#6c6f85', '#bcc0cc', '#1e66f5', '#d20f39'],
    dark: ['#1e1e2e', '#181825', '#cdd6f4', '#313244', '#a6adc8', '#45475a', '#89b4fa', '#f38ba8'],
  },
  nord: {
    light: ['#eceff4', '#e5e9f0', '#2e3440', '#d8dee9', '#4c566a', '#c2cad8', '#5e81ac', '#bf616a'],
    dark: ['#2e3440', '#3b4252', '#eceff4', '#434c5e', '#d8dee9', '#4c566a', '#88c0d0', '#bf616a'],
  },
  solarized: {
    light: ['#fdf6e3', '#eee8d5', '#586e75', '#eee8d5', '#657b83', '#d9d2bd', '#268bd2', '#dc322f'],
    dark: ['#002b36', '#073642', '#93a1a1', '#073642', '#839496', '#586e75', '#2aa198', '#dc322f'],
  },
  gruvbox: {
    light: ['#fbf1c7', '#ebdbb2', '#3c3836', '#ebdbb2', '#665c54', '#d5c4a1', '#076678', '#9d0006'],
    dark: ['#282828', '#3c3836', '#ebdbb2', '#3c3836', '#bdae93', '#504945', '#83a598', '#fb4934'],
  },
  'rose-pine': {
    light: ['#faf4ed', '#fffaf3', '#575279', '#f2e9e1', '#797593', '#dfdad9', '#286983', '#b4637a'],
    dark: ['#191724', '#1f1d2e', '#e0def4', '#26233a', '#908caa', '#403d52', '#c4a7e7', '#eb6f92'],
  },
  'tokyo-night': {
    light: ['#e1e2e7', '#d5d6db', '#3760bf', '#c4c8da', '#6172b0', '#b4b5b9', '#2e7de9', '#f52a65'],
    dark: ['#1a1b26', '#16161e', '#c0caf5', '#292e42', '#a9b1d6', '#3b4261', '#7aa2f7', '#f7768e'],
  },
}
export const LABELS = { default: 'Default', catppuccin: 'Catppuccin (Latte / Mocha)', nord: 'Nord (Snow Storm / Polar Night)', solarized: 'Solarized', gruvbox: 'Gruvbox', 'rose-pine': 'Rosé Pine (Dawn / Main)', 'tokyo-night': 'Tokyo Night (Day / Night)' }

// Approximations of the existing neutral shadcn theme, used only to derive its chart colors.
const DEFAULT_SURFACE = { light: ['#ffffff', '#ffffff', '#0f172a', '#f1f5f9'], dark: ['#020618', '#0b1224', '#f8fafc', '#1d293d'] }

// ---- chart palettes ----
// Fixed slot order (never cycled), found by random search so neighbours stay >=12 ΔE apart under
// protan/deutan in both modes. [hue, lightness step]: steps spread L so red/green differ in lightness.
const SLOTS = [[255, 2], [25, 2], [235, 4], [150, 0], [350, 4], [80, 0], [300, 2], [55, 1], [178, 4]]
const STEP = { light: [-0.08, -0.04, 0, 0.04, 0.07], dark: [-0.05, -0.025, 0, 0.025, 0.05] }
// [L, C] base of categorical marks per scheme and mode. Muted schemes (nord) get lower chroma.
const L0 = { light: 0.57, dark: 0.61 }
const CHROMA = { default: [0.18, 0.15], catppuccin: [0.17, 0.14], nord: [0.14, 0.15], solarized: [0.16, 0.13], gruvbox: [0.16, 0.14], 'rose-pine': [0.15, 0.13], 'tokyo-night': [0.18, 0.15] }
export function chartColors(scheme, mode, bg, card, fg) {
  const L = L0[mode], C = CHROMA[scheme][mode === 'light' ? 0 : 1]
  const cat = SLOTS.map(([h, k]) => fromOklch(L + STEP[mode][k], C, h))
  const [, , bgH] = toOklch(bg)
  const strategy = fromOklch(L - 0.06 * (mode === 'light' ? 1 : -1), C + 0.04, 255)
  const gray = fromOklch(mode === 'light' ? 0.6 : 0.68, 0.03, bgH)
  const out = {
    'chart-strategy': strategy,
    'chart-bh': gray, // benchmarks: low chroma so they stay secondary; charts also dash them
    'chart-6040': fromOklch(L + 0.03, 0.07, 55),
    'chart-ew': fromOklch(L + 0.03, 0.07, 195),
    'div-neg': fromOklch(L + 0.02, 0.17, 35),
    'div-pos': fromOklch(L + 0.02, 0.12, 195),
  }
  cat.forEach((c, i) => (out[`chart-${i + 1}`] = c))
  return { out, cat, surface: card }
}

// ---- emit ----
const fmt = (o) => Object.entries(o).map(([k, v]) => `  --${k}: ${v};`).join('\n')
let css = '/* GENERATED by scripts/gen-schemes.mjs — do not edit. Official scheme colors + derived chart palettes. */\n'
const report = []
for (const scheme of ['default', ...Object.keys(S)]) {
  for (const mode of ['light', 'dark']) {
    let base = {}
    let bg, card, fg, mutedBg
    if (scheme === 'default') [bg, card, fg, mutedBg] = DEFAULT_SURFACE[mode]
    else {
      let [bg0, card0, fg0, mut, mfg, border, prim, destr] = S[scheme][mode]
      ;[bg, card, fg, mutedBg] = [bg0, card0, fg0, mut]
      fg = ensure(fg0, [bg, card, mut], 4.5)
      const mutedFg = ensure(mfg, [bg, card, mut], 4.5)
      const dark = mode === 'dark'
      let primary = prim
      const onPrim = (p) => [dark ? bg : '#ffffff', dark ? '#ffffff' : bg].filter(Boolean).sort((a, b) => contrast(b, p) - contrast(a, p))[0]
      while (contrast(onPrim(primary), primary) < 4.5) { const [L, C, H] = toOklch(primary); primary = fromOklch(L + (dark ? 0.01 : -0.01), C, H) }
      Object.assign(base, {
        background: bg, foreground: fg, card, 'card-foreground': fg, popover: card, 'popover-foreground': fg,
        primary, 'primary-foreground': onPrim(primary), secondary: mut, 'secondary-foreground': fg,
        muted: mut, 'muted-foreground': mutedFg, accent: mut, 'accent-foreground': fg,
        destructive: ensure(destr, [bg], 3), border, input: border, ring: primary,
      })
    }
    const { out, cat, surface } = chartColors(scheme, mode, bg, card, fg)
    // each chart mark needs >=3:1 against the card it sits on
    for (const [k, v] of Object.entries(out)) if (contrast(v, surface) < 3) out[k] = ensure(v, [surface], 3)
    const sel = scheme === 'default' ? `[data-scheme="default"]${mode === 'dark' ? '.dark' : ''}` : mode === 'dark' ? `.dark[data-scheme="${scheme}"]` : `[data-scheme="${scheme}"]`
    css += `\n${sel} {\n${fmt({ ...base, ...out, 'div-neu': mutedBg })}\n}\n`
    report.push({ scheme, mode, cat: SLOTS.map((_, i) => out[`chart-${i + 1}`]), surface })
  }
}
writeFileSync(new URL('../src/styles/schemes.css', import.meta.url), css)
console.log(`wrote schemes.css (${report.length} scheme/mode blocks)`)

const vi = process.argv.indexOf('--validate')
if (vi > 0) {
  for (const r of report) {
    let txt
    try { txt = execFileSync('node', [process.argv[vi + 1], r.cat.join(','), '--mode', r.mode, '--surface', r.surface], { encoding: 'utf8' }) } catch (e) { txt = e.stdout }
    const lines = txt.split('\n').filter((l) => /\[(PASS|WARN|FAIL)\]/.test(l)).map((l) => l.replace(/\s+/g, ' ').slice(0, 120))
    console.log(`\n${r.scheme} ${r.mode} ${r.surface}`); lines.forEach((l) => console.log(' ', l))
  }
}
